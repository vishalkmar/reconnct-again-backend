// GET /api/public/geo/nearby
const nearby = asyncHandler(async (req, res) => {
  const city = req.query.city || 'your area';
  const base = process.env.LLM_BASE_URL;
  const key = process.env.LLM_API_KEY;
  const model = process.env.LLM_MODEL;

  if (base && key && model) {
    const prompt = `List 4 famous places or experiences within a few kilometres of ${city}`
      + `${req.query.lat ? ` (near ${req.query.lat},${req.query.lon})` : ''}. `
      + 'Respond ONLY with strict JSON: an array of objects with keys '
      + '"name", "distanceText" (e.g. "1.5 km away"), "blurb" (max 14 words). No prose.';
    const j = await safeFetch(`${base.replace(/\/$/, '')}/chat/completions`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${key}` },
      body: JSON.stringify({
        model,
        messages: [{ role: 'user', content: prompt }],
        temperature: 0.4, max_tokens: 400,
      }),
    }, 9000);
    const text = j && j.choices && j.choices[0] && j.choices[0].message && j.choices[0].message.content;
    if (text) {
      try {
        const cleaned = text.replace(/```json|```/g, '').trim();
        const arr = JSON.parse(cleaned);
        if (Array.isArray(arr) && arr.length) {
          return ok(res, { city, source: 'llm', places: arr.slice(0, 6) });
        }
      } catch { /* fall through to static */ }
    }
  }

  return ok(res, { city, source: 'static', places: STATIC_NEARBY(city) });
});

