// Generic hero image used only when we truly can't find anything else — the
// "You are here" card must NEVER be blank.
// A NEUTRAL cityscape (not a specific monument) so a fallback never implies the
// wrong place.
const GENERIC_IMAGE = 'https://images.unsplash.com/photo-1480714378408-67cf0d13bc1b?w=800&q=80';

// Bump a Wikipedia thumbnail URL up to ~800px wide. Wikimedia thumb URLs end in
// "/<n>px-Name.jpg" — swapping the size gives a bigger yet still light image
// (the full originalimage can be several MB and often fails to load on mobile).
const upsizeWikiThumb = (url) => {
  if (!url) return url;
  return url.replace(/\/(\d+)px-/, '/800px-');
};

// Look up a real lead photo for a place from Wikipedia (free, no key). Prefers
// a right-sized thumbnail (reliable on mobile) over the heavy originalimage.
const wikiSummary = async (title) => {
  if (!title) return null;
  const j = await safeFetch(
    `https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(title)}`,
    { headers: { 'User-Agent': 'reconnct-app/1.0 (support@reconnct.app)' } },
  );
  if (!j || j.type === 'disambiguation') return null;
  const img = (j.thumbnail && upsizeWikiThumb(j.thumbnail.source))
    || (j.originalimage && j.originalimage.source) || null;
  if (!img) return null;
  return { name: j.title || title, image: img, blurb: j.extract || '', link: (j.content_urls && j.content_urls.desktop && j.content_urls.desktop.page) || null };
};

// Ask the LLM for ONE famous, photographable landmark closest to the user's
// exact spot — a metro station, mall, monument or market in this area — so the
// "You are here" hero shows something the user will actually recognise around
// them, not just a generic city photo. Returns null if the LLM isn't configured.
const landmarkNear = async ({ area, city }) => {
  const base = process.env.LLM_BASE_URL;
  const key = process.env.LLM_API_KEY;
  const model = process.env.LLM_MODEL;
  if (!base || !key || !model || (!area && !city)) return null;
  const where = [area, city].filter(Boolean).join(', ');
  const prompt = 'Name ONE real, well-photographed place NEAR this exact location, choosing in this '
    + 'STRICT priority order: 1) a famous monument / tourist landmark nearby; else '
    + '2) a big shopping mall or shopping complex nearby; else 3) the nearest metro station. '
    + 'It must genuinely be in or beside this area (not a distant city). Reply with ONLY its '
    + 'common Wikipedia-style name, no address, no extra words.\n'
    + `Location: "${where}"`;
  const j = await safeFetch(`${base.replace(/\/$/, '')}/chat/completions`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${key}` },
    body: JSON.stringify({ model, messages: [{ role: 'user', content: prompt }], temperature: 0.2, max_tokens: 24 }),
  }, 8000);
  const text = j && j.choices && j.choices[0] && j.choices[0].message && j.choices[0].message.content;
  if (!text) return null;
  const name = String(text).trim().replace(/^["'\s]+|["'.\s]+$/g, '').split('\n')[0].trim();
  return name && name.length <= 60 ? name : null;
};

// GET /api/public/geo/place-image?city=&area=&place=
// A single "You are here" hero: a famous place NEAR the user's exact spot + its
// real photo. Order: an explicit place → an LLM-picked nearby landmark (metro/
// mall/monument for this area) → the city → a curated fallback image.
const placeImage = asyncHandler(async (req, res) => {
  const city = String(req.query.city || '').trim();
  const area = String(req.query.area || '').trim();
  const place = String(req.query.place || '').trim();

  // If the caller didn't name a place, let the LLM find the closest famous one.
  const landmark = place || (await landmarkNear({ area, city }));

  const titles = [
    landmark,
    landmark && city ? `${landmark}, ${city}` : '',
    area && city ? `${area}, ${city}` : '',
    city,
  ].filter(Boolean);
  for (const title of titles) {
    // eslint-disable-next-line no-await-in-loop
    const hit = await wikiSummary(title);
    if (hit) return ok(res, { ...hit, city: city || null, area: area || null, source: 'wikipedia' });
  }
  // Image is mandatory for the "You are here" card — never return null.
  const fallback = CITY_IMAGE[city.toLowerCase()] || GENERIC_IMAGE;
  return ok(res, {
    name: landmark || area || city || 'Near you',
    image: fallback,
    blurb: '',
    link: null,
    city: city || null,
    area: area || null,
    source: CITY_IMAGE[city.toLowerCase()] ? 'curated' : 'generic',
  });
});

